#!/bin/sh
# Boot kernel stage 15's panic-semantics example once per check and assert the
# exact serial line each one prints: the message, the file name and the 1-based
# source line the compiler's check named. One boot can show one check, because
# a panic ends the machine, so `selector.which()` picks the check and this
# script rewrites that one file in a scratch copy.
#
# The double-panic phase also proves the *project-defined* `kelp_double_panic`:
# the compiler emits a weak wait-for-interrupt fallback, `double_panic.s` is a
# strong definition linked beside the object, and the phase only prints
# `double panic` if that definition won.
#
# It has to run where `kelpc` was built and where `qemu-system-riscv64`,
# `ld.lld` and `llvm-mc` are on PATH, that is the repo's `dev-kernel.nix` shell.
# Set KELPC to point at another binary. The assertion is against QEMU's own
# stdout, not against the source's intent.
#
# Usage, from anywhere:  examples/kernel0-panic2/run.sh [project-dir]
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
project=${1:-$here}

kelpc=${KELPC:-$repo/target/debug/kelpc}
if [ ! -x "$kelpc" ]; then
    echo "run.sh: no kelpc at $kelpc (build it in dev-kernel.nix, or set KELPC)" >&2
    exit 1
fi
for tool in qemu-system-riscv64 ld.lld llvm-mc; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "run.sh: $tool is not on PATH (run me in dev-kernel.nix)" >&2
        exit 1
    fi
done

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
proj=$work/project
cp -R "$project" "$proj"

# The 1-based line of the statement the check was inserted into, taken from the
# same file the compiler read.
line_of() {
    grep -n "panic-line: $1" "$proj/src/main.kp" | head -1 | cut -d: -f1
}

run_phase() {
    phase=$1
    expect=$2
    printf '// Generated by run.sh: the check this boot exercises.\npub fun which() => u32 = %s\n' \
        "$phase" > "$proj/src/selector.kp"
    base=$work/phase$phase
    "$kelpc" build "$proj" -o "$base.elf"
    llvm-mc -triple=riscv64-unknown-none-elf -filetype=obj \
        -o "$base.dp.o" "$proj/double_panic.s"
    ld.lld -T "$proj/kernel.ld" -o "$base.linked.elf" --static \
        "$base.o" "$base.dp.o"

    serial=$base.serial
    timeout 20 qemu-system-riscv64 \
        -machine virt \
        -bios none \
        -nographic \
        -no-reboot \
        -serial mon:stdio \
        -kernel "$base.linked.elf" >"$serial" 2>/dev/null </dev/null &
    qpid=$!

    i=0
    while [ "$i" -lt 200 ]; do
        if grep -qF "$expect" "$serial" 2>/dev/null; then
            break
        fi
        if ! kill -0 "$qpid" 2>/dev/null; then
            break
        fi
        i=$((i + 1))
        sleep 0.1
    done
    kill "$qpid" 2>/dev/null || true
    wait "$qpid" 2>/dev/null || true

    if ! grep -qF "$expect" "$serial"; then
        echo "run.sh: phase $phase did not print '$expect'" >&2
        echo "run.sh: captured serial output:" >&2
        cat "$serial" >&2
        return 1
    fi
    printf 'phase %s: %s\n' "$phase" "$expect"
}

# Four compiler checks that carry a `main.kp` line, one that panics inside
# `std/option.kp`, and the double panic. `str.byte`'s check and the `unwrap`
# panic live in the stdlib bodies, so their locations name `str.kp`/`option.kp`.
strbyte_line=$(grep -n '^fun byte(' "$repo/kelpc/std/str.kp" | head -1 | cut -d: -f1)
unwrap_line=$(grep -n 'Option.unwrap: value is None' "$repo/kelpc/std/option.kp" | head -1 | cut -d: -f1)
run_phase 1 "panic: Array.get: index out of bounds at main.kp:$(line_of array)"
run_phase 2 "panic: i32.to_u8: value out of range at main.kp:$(line_of narrow)"
run_phase 3 "panic: str.byte: index out of bounds at str.kp:$strbyte_line"
run_phase 4 "panic: deliberate panic at main.kp:$(line_of explicit)"
run_phase 5 "panic: Option.unwrap: value is None at option.kp:$unwrap_line"
run_phase 6 "double panic"

echo "run.sh: all six phases printed the lines the compiler named"
