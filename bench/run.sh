#!/bin/sh
# Kelp vs C vs Rust benchmark harness. Run it inside the dev shell (it needs cc, rustc, cargo and the
# LLVM build half that kelpc links against):
#
#   nix-shell overnight/dev.nix --run 'sh bench/run.sh'
#
# What it does:
#   1. builds kelpc (release) unless $KELPC names a prebuilt one;
#   2. builds every bench/suite/<name>/<name>.{c,rs,kp} with each toolchain, 3 builds each, and
#      records the median build time;
#   3. runs every binary once as a discarded warm-up and then 7 times, each run under
#      `( ulimit -v 4194304; ulimit -t 300; timeout 300 ... )`, recording wall time, peak RSS and
#      whether stdout equals the C (gcc) version's checksum line; also records the stripped binary
#      size and the 1-minute load average before and after each block of runs;
#   4. writes bench/results.csv (raw, long form: bench,variant,metric,idx,value) and bench/RESULTS.md
#      (machine, tool versions, one table per metric, then bench/notes.md and, when present, the
#      bench/baseline-tables.md of the first recorded run).
#
# Knobs (environment): BENCHES="fib nbody" (subset), RUNS=7, BUILD_RUNS=3, KELPC=/path/to/kelpc,
# OUT_DIR (where results.csv/RESULTS.md go, default bench/), SIZE_ARG="" (a first argument handed to
# every benchmark; empty = the full default size, which is what RESULTS.md must be made with).
#
# POSIX sh plus GNU date (%N), GNU time (-f %M -o), awk, nice, timeout, strip and stat -c.
set -u

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
SUITE="$HERE/suite"
BUILD="$HERE/build"
OUT_DIR=${OUT_DIR:-$HERE}
CSV="$OUT_DIR/results.csv"
MD="$OUT_DIR/RESULTS.md"
RUNS=${RUNS:-7}
BUILD_RUNS=${BUILD_RUNS:-3}
SIZE_ARG=${SIZE_ARG:-}
ALL_BENCHES="fib nbody spectral-norm mandelbrot binary-trees fannkuch-redux sieve matmul strings hashmap sort sort-builtin json-tokenizer"
BENCHES=${BENCHES:-$ALL_BENCHES}

TIME_BIN=""
for t in /usr/bin/time /run/current-system/sw/bin/time $(IFS=:; for p in $PATH; do echo "$p/time"; done); do
    if [ -x "$t" ] && [ ! -d "$t" ]; then TIME_BIN=$t; break; fi
done
if [ -z "$TIME_BIN" ]; then
    echo "run.sh: GNU time not found" >&2
    exit 1
fi

mkdir -p "$BUILD" "$OUT_DIR"

now_ns() { date +%s%N; }
load1() { cut -d' ' -f1 /proc/loadavg; }
secs_between() { awk -v a="$1" -v b="$2" 'BEGIN { printf "%.4f", (b - a) / 1e9 }'; }

# ---------------------------------------------------------------- compiler
if [ -z "${KELPC:-}" ]; then
    echo "building kelpc (release, not counted)..." >&2
    ( cd "$ROOT" && cargo build -q --release -p kelpc ) || { echo "run.sh: cargo build failed" >&2; exit 1; }
    KELPC="${CARGO_TARGET_DIR:-$ROOT/target}/release/kelpc"
fi
[ -x "$KELPC" ] || { echo "run.sh: no kelpc at $KELPC" >&2; exit 1; }
# kelpc's object cache is opt-in (--incremental), so a plain `build` never reuses an earlier object
# and the three builds are three real builds.

HAVE_CLANG=0
command -v clang >/dev/null 2>&1 && HAVE_CLANG=1

VARIANTS="c-gcc"
[ "$HAVE_CLANG" = 1 ] && VARIANTS="$VARIANTS c-clang"
VARIANTS="$VARIANTS rust kelp-llvm kelp-c"

: > "$CSV"
csv() { printf '%s,%s,%s,%s,%s\n' "$1" "$2" "$3" "$4" "$5" >> "$CSV"; }

# build_cmd VARIANT SRCDIR NAME BIN
build_one() {
    v=$1; d=$2; n=$3; bin=$4
    case "$v" in
        c-gcc)     cc -O2 -o "$bin" "$d/$n.c" -lm ;;
        c-clang)   clang -O2 -o "$bin" "$d/$n.c" -lm ;;
        rust)      rustc -C opt-level=3 -o "$bin" "$d/$n.rs" ;;
        kelp-llvm) "$KELPC" build -O2 "$d/$n.kp" -o "$bin" ;;
        kelp-c)    KELPC_ORACLE=c "$KELPC" build -O2 "$d/$n.kp" -o "$bin" ;;
    esac
}

# run_one BIN OUTFILE -> sets RUN_WALL, RUN_RSS, RUN_RC
run_one() {
    rssf="$BUILD/.rss"
    : > "$rssf"
    t0=$(now_ns)
    ( ulimit -v 4194304; ulimit -t 300; exec timeout 300 "$TIME_BIN" -f '%M' -o "$rssf" nice -n 0 "$1" $SIZE_ARG ) > "$2" 2> "$BUILD/.err"
    RUN_RC=$?
    t1=$(now_ns)
    RUN_WALL=$(secs_between "$t0" "$t1")
    RUN_RSS=$(tail -n 1 "$rssf" 2>/dev/null | tr -dc '0-9')
    [ -n "$RUN_RSS" ] || RUN_RSS=0
}

# ------------------------------------------------------------ machine info
{
    echo "# Kelp benchmark results"
    echo
    echo "Generated by \`bench/run.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC'). Do not edit by hand: the"
    echo "tables are regenerated from \`bench/results.csv\`; the prose lives in \`bench/notes.md\`."
    echo
    echo "## Machine and tools"
    echo
    echo "- CPU: $(grep -m1 'model name' /proc/cpuinfo | sed 's/.*: //'), $(grep -c '^processor' /proc/cpuinfo) logical CPUs"
    echo "- Memory: $(awk '/MemTotal/ { printf "%.1f GB", $2 / 1048576 }' /proc/meminfo) total, $(awk '/SwapTotal/ { printf "%.1f GB", $2 / 1048576 }' /proc/meminfo) swap"
    echo "- Kernel: $(uname -srm)"
    echo "- Load average at start: $(cut -d' ' -f1-3 /proc/loadavg)"
    echo "- gcc: $(cc --version 2>&1 | head -1)"
    if [ "$HAVE_CLANG" = 1 ]; then
        echo "- clang: $(clang --version 2>&1 | head -1)"
    else
        echo "- clang: not available on this machine, so no C (clang) rows"
    fi
    echo "- rustc: $(rustc --version 2>&1 | head -1)"
    echo "- kelpc: $("$KELPC" version 2>&1 | head -1) ($("$KELPC" version --verbose 2>&1 | grep -i -m1 -E 'commit|git|rev' || echo 'no commit info'))"
    echo "- Builds: C \`cc -O2\`; Rust \`rustc -C opt-level=3\` (bounds checks and overflow wrapping as in the source; no cargo, no LTO); Kelp \`kelpc build -O2\` on the default LLVM backend (\`kelp-llvm\`) and with \`KELPC_ORACLE=c\` (\`kelp-c\`, the C oracle backend, compiled by the same \`cc -O2\`). No \`-march=native\`, no \`-ffast-math\`, no SIMD intrinsics."
    echo "- Bounds checks: ON in Kelp (both backends) and in Rust (indexing); OFF in C. This is a stated asymmetry in C's favour."
    echo "- Method: each benchmark is built ${BUILD_RUNS} times (median build time), then run once as a discarded warm-up and ${RUNS} times, always with the full default size (first-argument override: \`${SIZE_ARG:-none}\`), each run under \`( ulimit -v 4194304; ulimit -t 300; timeout 300 time nice -n 0 ... )\`. Wall time is read with \`date +%s%N\` around the whole wrapper (includes about 1-3 ms of fork/exec of \`timeout\`/\`time\`/\`nice\`, the same for every row), peak RSS from GNU \`time %M\`. A row's checksum status compares the program's stdout with the gcc C version's stdout on every run."
    echo "- Noise: other processes run on this host (a Minecraft server, other agents' builds). The 1-minute load average is read before and after each block of runs; a row is flagged NOISY when it changed by more than 1.0. Nothing is stopped or throttled to quiet the host."
    echo
} > "$BUILD/header.md"

# --------------------------------------------------------------- main loop
echo "benchmarks: $BENCHES" >&2
echo "variants:   $VARIANTS" >&2

# fork/exec overhead of the measurement wrapper itself (the same for every row)
i=1
while [ "$i" -le "$RUNS" ]; do
    run_one /bin/true "$BUILD/.out"
    csv "(wrapper)" "true" "wall_s" "$i" "$RUN_WALL"
    i=$((i + 1))
done

for n in $BENCHES; do
    d="$SUITE/$n"
    mkdir -p "$BUILD/$n"
    ref=""
    for v in $VARIANTS; do
        bin="$BUILD/$n/$v"
        rm -f "$bin"
        # ---- build, BUILD_RUNS times
        ok=1
        i=1
        while [ "$i" -le "$BUILD_RUNS" ]; do
            rm -f "$bin"
            t0=$(now_ns)
            build_one "$v" "$d" "$n" "$bin" > "$BUILD/$n/$v.build.log" 2>&1
            rc=$?
            t1=$(now_ns)
            if [ "$rc" -ne 0 ] || [ ! -x "$bin" ]; then
                ok=0
                break
            fi
            csv "$n" "$v" "build_s" "$i" "$(secs_between "$t0" "$t1")"
            i=$((i + 1))
        done
        if [ "$ok" = 0 ]; then
            echo "  $n/$v: BUILD FAILED (see $BUILD/$n/$v.build.log)" >&2
            csv "$n" "$v" "check" 0 "BUILD-FAILED"
            continue
        fi
        # ---- size, stripped
        cp "$bin" "$bin.stripped" && strip "$bin.stripped" 2>/dev/null
        csv "$n" "$v" "size_b" 0 "$(stat -c %s "$bin.stripped")"
        rm -f "$bin.stripped"
        # ---- runs: warm-up + RUNS
        l0=$(load1)
        status=ok
        i=0
        while [ "$i" -le "$RUNS" ]; do
            run_one "$bin" "$BUILD/$n/$v.out.$i"
            if [ "$RUN_RC" -ne 0 ]; then
                status="FAILED(exit $RUN_RC)"
                case "$RUN_RC" in 124|137|152) status="TIMEOUT(300s limit)" ;; esac
                break
            fi
            if [ "$v" = "c-gcc" ] && [ "$i" -eq 0 ]; then
                cp "$BUILD/$n/$v.out.0" "$BUILD/$n/reference.out"
                ref="$BUILD/$n/reference.out"
            fi
            if [ -n "$ref" ]; then
                cmp -s "$ref" "$BUILD/$n/$v.out.$i" || status="MISMATCH"
            else
                status="no-reference"
            fi
            if [ "$i" -gt 0 ]; then
                csv "$n" "$v" "wall_s" "$i" "$RUN_WALL"
                csv "$n" "$v" "rss_kb" "$i" "$RUN_RSS"
            fi
            i=$((i + 1))
        done
        l1=$(load1)
        csv "$n" "$v" "load_before" 0 "$l0"
        csv "$n" "$v" "load_after" 0 "$l1"
        csv "$n" "$v" "check" 0 "$status"
        echo "  $n/$v: $status  load $l0 -> $l1" >&2
    done
done

# ------------------------------------------------------------ the tables
awk -F, -v runs="$RUNS" -v bruns="$BUILD_RUNS" -v variants="$VARIANTS" -v benches="$BENCHES" '
function median(key,   n, i, j, t, a) {
    n = cnt[key]
    if (n == 0) return ""
    for (i = 1; i <= n; i++) a[i] = val[key, i]
    for (i = 2; i <= n; i++) { t = a[i]; for (j = i - 1; j >= 1 && a[j] > t; j--) a[j + 1] = a[j]; a[j + 1] = t }
    if (n % 2 == 1) return a[(n + 1) / 2]
    return (a[n / 2] + a[n / 2 + 1]) / 2
}
function minv(key,   i, m) { m = val[key, 1]; for (i = 2; i <= cnt[key]; i++) if (val[key, i] < m) m = val[key, i]; return m }
function maxv(key,   i, m) { m = val[key, 1]; for (i = 2; i <= cnt[key]; i++) if (val[key, i] > m) m = val[key, i]; return m }
function ratio(b, v, metric,   m, r) {
    r = b SUBSEP "c-gcc" SUBSEP metric
    m = b SUBSEP v SUBSEP metric
    if (cnt[m] == 0 || cnt[r] == 0 || median(r) == 0) return "n/a"
    return sprintf("%.2f", median(m) / median(r))
}
function noisy(b, v,   d) {
    d = lb[b, v] - la[b, v]; if (d < 0) d = -d
    if (!((b, v) in lb)) return ""
    return (d > 1.0) ? "NOISY (load " lb[b, v] " to " la[b, v] ")" : "load " lb[b, v] " to " la[b, v]
}
function table(metric, title, unit, scale, fmt,   bi, vi, b, v, k, m) {
    print "### " title; print ""
    print "| benchmark | variant | median " unit " | min | max | ratio to C (gcc) | checksum | load |"
    print "| --- | --- | ---: | ---: | ---: | ---: | --- | --- |"
    for (bi = 1; bi <= nb; bi++) for (vi = 1; vi <= nv; vi++) {
        b = B[bi]; v = V[vi]; k = b SUBSEP v SUBSEP metric
        if (cnt[k] == 0) { printf "| %s | %s | - | - | - | - | %s | |\n", b, v, chk[b, v]; continue }
        printf "| %s | %s | " fmt " | " fmt " | " fmt " | %s | %s | %s |\n", b, v, median(k) / scale, minv(k) / scale, maxv(k) / scale, ratio(b, v, metric), chk[b, v], noisy(b, v)
    }
    print ""
}
function onecol(metric, title, unit, scale, fmt,   bi, vi, b, v, k) {
    print "### " title; print ""
    print "| benchmark | variant | " unit " | ratio to C (gcc) | checksum |"
    print "| --- | --- | ---: | ---: | --- |"
    for (bi = 1; bi <= nb; bi++) for (vi = 1; vi <= nv; vi++) {
        b = B[bi]; v = V[vi]; k = b SUBSEP v SUBSEP metric
        if (cnt[k] == 0) { printf "| %s | %s | - | - | %s |\n", b, v, chk[b, v]; continue }
        printf "| %s | %s | " fmt " | %s | %s |\n", b, v, median(k) / scale, ratio(b, v, metric), chk[b, v]
    }
    print ""
}
BEGIN { nb = split(benches, B, " "); nv = split(variants, V, " ") }
{
    b = $1; v = $2; m = $3; x = $5
    if (m == "check") { chk[b, v] = x; next }
    if (m == "load_before") { lb[b, v] = x; next }
    if (m == "load_after") { la[b, v] = x; next }
    k = b SUBSEP v SUBSEP m
    cnt[k]++; val[k, cnt[k]] = x + 0
}
END {
    print "## Summary: wall time relative to C (gcc -O2), median of " runs " runs"; print ""
    printf "| benchmark |"; for (vi = 1; vi <= nv; vi++) printf " %s |", V[vi]; print ""
    printf "| --- |"; for (vi = 1; vi <= nv; vi++) printf " ---: |"; print ""
    for (bi = 1; bi <= nb; bi++) {
        b = B[bi]; printf "| %s |", b
        for (vi = 1; vi <= nv; vi++) {
            v = V[vi]; c = chk[b, v]
            if (c != "ok") printf " %s |", c
            else printf " %s%s |", ratio(b, v, "wall_s"), (noisy(b, v) ~ /^NOISY/ ? " (noisy)" : "")
        }
        print ""
    }
    print ""
    print "Every ratio above 1.5 is explained in the analysis section below."; print ""
    w = "(wrapper)" SUBSEP "true" SUBSEP "wall_s"
    printf "Measurement wrapper overhead (`timeout`+`time`+`nice` around /bin/true): median %.1f ms, included in every wall time.\n\n", median(w) * 1000
    print "## Detailed tables"; print ""
    table("wall_s", "Wall time", "(s)", 1, "%.3f")
    table("rss_kb", "Peak resident set size", "(MB)", 1024, "%.1f")
    onecol("size_b", "Binary size, stripped", "(KB)", 1024, "%.1f")
    table("build_s", "Build time (" bruns " builds each, kelpc incremental cache off)", "(s)", 1, "%.2f")
}' "$CSV" > "$BUILD/tables.md"

{
    cat "$BUILD/header.md"
    cat "$BUILD/tables.md"
    if [ -f "$HERE/notes.md" ]; then
        cat "$HERE/notes.md"
        echo
    fi
    if [ -f "$HERE/baseline-tables.md" ]; then
        echo "## First run (baseline, before any compiler change)"
        echo
        echo "Kept verbatim so that any later improvement is measured against it. Raw data: \`bench/baseline-results.csv\`."
        echo
        cat "$HERE/baseline-tables.md"
    fi
} > "$MD"

echo "wrote $CSV and $MD" >&2
